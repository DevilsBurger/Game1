# -*- coding: utf-8 -*-
"""
server/openapi.yaml → unity/Generated/NetDtos.cs (Arken.Net.Generated): 요청/응답 DTO, 에러 코드 상수, 라우트 상수.
규칙: 필드 이름은 JSON과 동일(snake_case, Unity JsonUtility/Newtonsoft 모두 그대로 매핑), int64 → long, number → double,
      array → List<T>, additionalProperties → Dictionary<string, T>, 자유 object → Dictionary<string, object>, enum(string) → string + 상수 클래스.
      인라인 객체는 '{부모}_{필드}' 중첩 클래스. Unity 의존 없음(서버 .NET 공용).
"""
import os, re, yaml

ROOT = os.path.join(os.path.dirname(__file__), "..")
SPEC = yaml.safe_load(open(os.path.join(ROOT, "server", "openapi.yaml"), encoding="utf-8"))
OUT = os.path.join(ROOT, "unity", "Generated", "NetDtos.cs")
HEADER = "// <auto-generated> tools/gen_netdtos.py — 수정 금지. server/openapi.yaml을 바꾸고 재생성하세요. </auto-generated>\n"
SCHEMAS = SPEC["components"]["schemas"]
extra_classes = []   # 인라인 객체용 중첩 클래스
enum_consts = {}     # 클래스.필드 → enum 값들


def pascal(s):
    return "".join(p[:1].upper() + p[1:] for p in re.split(r"[^A-Za-z0-9]+", s) if p)


def cs_type(schema, owner, field):
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    t = schema.get("type")
    if isinstance(t, list):
        t = next((x for x in t if x != "null"), "string")
    if "enum" in schema and t == "string":
        enum_consts[f"{owner}.{field}"] = schema["enum"]
        return "string"
    if t == "string": return "string"
    if t == "integer": return "long" if schema.get("format") == "int64" else "int"
    if t == "number": return "double"
    if t == "boolean": return "bool"
    if t == "array":
        return f"List<{cs_type(schema.get('items', {}), owner, field)}>"
    if t == "object" or "properties" in schema or "additionalProperties" in schema:
        if "properties" in schema:
            name = f"{owner}_{pascal(field)}"
            extra_classes.append((name, schema))
            return name
        ap = schema.get("additionalProperties")
        if isinstance(ap, dict) and ap:
            return f"Dictionary<string, {cs_type(ap, owner, field)}>"
        return "Dictionary<string, object>"
    return "object"


def class_cs(name, schema, indent="    "):
    L = []
    desc = schema.get("description")
    if desc: L.append(f"{indent}/// <summary>{desc.splitlines()[0]}</summary>")
    L.append(f"{indent}[System.Serializable]")
    L.append(f"{indent}public sealed class {name} {{")
    req = set(schema.get("required", []))
    for fname, fs in schema.get("properties", {}).items():
        ty = cs_type(fs, name, fname)
        note = fs.get("description")
        tags = []
        if fname in req: tags.append("required")
        if note: tags.append(note.splitlines()[0])
        if tags: L.append(f"{indent}    /// <summary>{' · '.join(tags)}</summary>")
        L.append(f"{indent}    public {ty} {fname};")
    L.append(f"{indent}}}")
    return "\n".join(L)


def main():
    body = []
    for name, schema in SCHEMAS.items():
        body.append(class_cs(name, schema))
    while extra_classes:
        name, schema = extra_classes.pop(0)
        body.append(class_cs(name, schema))
    # enum 상수
    consts = ["    /// <summary>문자열 enum 값 상수 (필드별)</summary>", "    public static class Enums {"]
    for key, vals in enum_consts.items():
        cls = pascal(key.replace(".", "_"))
        consts.append(f"        public static class {cls} {{ " + " ".join(f'public const string {pascal(str(v)) or "Value"}{"" if not str(v)[0].isdigit() else ""} = "{v}";' for v in vals) + " }")
    consts.append("    }")
    # 라우트
    routes = ["    /// <summary>엔드포인트 상수: Method + Path (경로 변수는 {name})</summary>", "    public static class Routes {"]
    for path, item in SPEC["paths"].items():
        for m, op in item.items():
            if m not in ("get", "post", "put", "patch", "delete"): continue
            oid = pascal(op["operationId"])
            idem = any(p.get("$ref", "").endswith("IdempotencyKey") for p in op.get("parameters", []))
            routes.append(f'        public const string {oid} = "{m.upper()} {path}";' + ("  // Idempotency-Key 필수" if idem else ""))
    routes.append("    }")
    errors = ["    public static class ErrorCodes {"] + [f'        public const string {c} = "{c}";' for c in SCHEMAS["Error"]["properties"]["code"]["enum"]] + ["    }"]
    src = HEADER + "using System.Collections.Generic;\n\nnamespace Arken.Net.Generated {\n" + "\n\n".join(body) + "\n\n" + "\n".join(errors) + "\n\n" + "\n".join(consts) + "\n\n" + "\n".join(routes) + "\n}\n"
    open(OUT, "w", encoding="utf-8").write(src)
    n_cls = src.count("public sealed class ")
    print(f"NetDtos.cs: {n_cls} classes, {len(enum_consts)} enum fields, {sum(1 for p in SPEC['paths'].values() for m in p if m in ('get','post','put','patch','delete'))} routes")


if __name__ == "__main__":
    main()
