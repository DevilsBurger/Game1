def pascal(s):
    return "".join(p.capitalize() for p in re.split(r"[^A-Za-z0-9]+", s) if p)


def enum_cs(name, values, with_string_map=True):
    L = [f"    public enum {name} {{ " + ", ".join(pascal(v) for v in values) + " }"]
    if with_string_map:
        L.append(f"    public static class {name}Ids {{")
        L.append(f"        public static readonly string[] Keys = {{ " + ", ".join(f'"{v}"' for v in values) + " };")
        L.append(f"        public static {name} Parse(string key) {{ var i = System.Array.IndexOf(Keys, key); if (i < 0) throw new System.ArgumentException(\"unknown {name}: \" + key); return ({name})i; }}")
        L.append(f"        public static string Key({name} v) => Keys[(int)v];")
        L.append("    }")
    return "\n".join(L)


